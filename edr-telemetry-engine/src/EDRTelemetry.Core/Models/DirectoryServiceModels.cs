namespace EDRTelemetry.Core.Models;

/// <summary>
/// Represents LDAP/Active Directory query events
/// </summary>
public class DirectoryServiceEvent : TelemetryEvent
{
    public string QueryFilter { get; set; } = string.Empty;
    public List<string> ObjectsQueried { get; set; } = new();
    public string SearchBase { get; set; } = string.Empty;
    public string SourceHost { get; set; } = string.Empty;
    public string SourceUser { get; set; } = string.Empty;
    public uint QueryCount { get; set; }
    public bool IsAnomalous { get; set; }
    public List<string> SuspiciousAttributes { get; set; } = new();
    
    // Common recon patterns
    public bool IsNTSecurityDescriptorQuery { get; set; }
    public bool IsBroadWildcardSearch { get; set; }
    public bool IsDACLEnumeration { get; set; }
}

/// <summary>
/// Represents an alert generated by analysis rules
/// </summary>
public class Alert
{
    public string AlertId { get; set; } = Guid.NewGuid().ToString();
    public DateTime DetectionTime { get; set; } = DateTime.UtcNow;
    public string RuleId { get; set; } = string.Empty;
    public string RuleName { get; set; } = string.Empty;
    public SeverityLevel Severity { get; set; } = SeverityLevel.Warning;
    public string Title { get; set; } = string.Empty;
    public string Description { get; set; } = string.Empty;
    public List<string> CorrelatedEventIds { get; set; } = new();
    public Dictionary<string, object> Context { get; set; } = new();
    public string RecommendedAction { get; set; } = string.Empty;
}
